// Regenerates the SVG icon registry used wherever an icon has to be a string (Leaflet divIcons, the tube iframe):
//   src/utils/svgIconData.ts  and  public/tube/svg-icons.js
// Paths are read from the installed lucide-react, so adding an icon is: add its kebab-case name below and run
//   node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const NAMES = [
  'heart', 'landmark', 'building-2', 'person-standing', 'music-4', 'drama', 'piano', 'crown', 'ghost', 'globe', 'star',
  'tree-pine', 'megaphone', 'spade', 'guitar', 'mic-vocal', 'mic', 'droplet', 'toilet', 'map-pin', 'footprints', 'bus',
  'plane', 'triangle-alert', 'check', 'search', 'chevron-right', 'arrow-up-down', 'theater', 'hat-glasses', 'circle-dot',
  'crosshair', 'ticket', 'sparkles', 'cloud-sun', 'waves', 'leaf',
  'bike', 'circle-parking', 'car-taxi-front', 'cloud-rain',
];

const dir = new URL('../node_modules/lucide-react/dist/esm/icons/', import.meta.url);
const registry = {};
for (const name of NAMES) {
  const { __iconNode } = await import(pathToFileURL(new URL(`${name}.js`, dir).pathname).href);
  registry[name] = __iconNode.map(([tag, { key, ...attrs }]) => [tag, attrs]);
}
const json = JSON.stringify(registry);

writeFileSync(
  new URL('../src/utils/svgIconData.ts', import.meta.url),
  `// Generated by scripts/gen-icons.mjs from lucide-react — do not edit by hand.\nexport type IconNode = [string, Record<string, string>][];\nexport const ICON_NODES: Record<string, IconNode> = ${json};\n`
);
writeFileSync(
  new URL('../public/tube/svg-icons.js', import.meta.url),
  `// Generated by scripts/gen-icons.mjs from lucide-react — do not edit by hand.
(function () {
  var NODES = ${json};
  // svgIcon('star', { size: 14, fill: true }) -> inline <svg> markup that inherits the current text colour.
  window.svgIcon = function (name, o) {
    o = o || {};
    var n = NODES[name] || NODES['theater'];
    var s = o.size || '1em';
    return '<svg class="svg-ico' + (o.className ? ' ' + o.className : '') + '" xmlns="http://www.w3.org/2000/svg" width="' + s + '" height="' + s +
      '" viewBox="0 0 24 24" fill="' + (o.fill ? 'currentColor' : 'none') + '" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
      n.map(function (e) { return '<' + e[0] + Object.keys(e[1]).map(function (k) { return ' ' + k + '="' + e[1][k] + '"'; }).join('') + '/>'; }).join('') + '</svg>';
  };
})();
`
);
console.log('icons:', Object.keys(registry).length);
